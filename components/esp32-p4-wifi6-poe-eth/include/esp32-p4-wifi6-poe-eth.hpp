namespace espp {
/// @brief Board Support Package (BSP) for the Waveshare ESP32-P4-WIFI6-POE-ETH board.
///
/// The ESP32-P4-WIFI6-POE-ETH pairs an ESP32-P4 (dual-core 360 MHz RISC-V,
/// 32 MB stacked PSRAM, 32 MB NOR flash) with an on-board ESP32-C6-MINI-1
/// (Wi-Fi 6 + Bluetooth 5 LE co-processor over SDIO) and a 10/100 RJ45
/// Ethernet port with a reserved header for a plug-in PoE power module.
///
/// This class provides a singleton interface to the board's peripherals:
/// - 10/100 Ethernet via the ESP32-P4 internal EMAC and an IP101GRI RMII PHY.
///   PoE is purely a power-supply feature (the RJ45 center taps feed bridge
///   rectifiers and a 5-pin header for Waveshare's PoE module, which produces
///   the board's 5 V rail) — no GPIO is involved, so a PoE-powered board looks
///   identical to a USB-powered one in software.
/// - The internal I2C bus (SDA=GPIO7, SCL=GPIO8), shared by the on-board
///   ES8311 audio codec (0x18) and the DSI/CSI connectors + 40-pin header.
///
/// Wi-Fi 6 / BLE are provided by the on-board ESP32-C6 over SDIO using
/// Espressif's ESP-Hosted + esp_wifi_remote components; espp does not (yet)
/// wrap that pattern in a BSP API, so this BSP documents the wiring (see the
/// pin constants below and the example README) instead of wrapping it:
///
/// <table>
/// <tr><th>Signal</th><th>ESP32-P4 GPIO</th><th>ESP32-C6 pin</th></tr>
/// <tr><td>SDIO CLK</td><td>18</td><td>IO19 (SDIO_CLK)</td></tr>
/// <tr><td>SDIO CMD</td><td>19</td><td>IO18 (SDIO_CMD)</td></tr>
/// <tr><td>SDIO D0</td><td>14</td><td>IO20 (SDIO_DATA0)</td></tr>
/// <tr><td>SDIO D1</td><td>15</td><td>IO21 (SDIO_DATA1)</td></tr>
/// <tr><td>SDIO D2</td><td>16</td><td>IO22 (SDIO_DATA2)</td></tr>
/// <tr><td>SDIO D3</td><td>17</td><td>IO23 (SDIO_DATA3)</td></tr>
/// <tr><td>C6 reset (CHIP_PU / EN)</td><td>54</td><td>EN</td></tr>
/// <tr><td>Spare cross-connect (0 Ω)</td><td>6</td><td>IO2</td></tr>
/// </table>
///
/// RMII pin mapping (ESP32-P4 routable EMAC pins; identical to the Waveshare
/// ESP32-P4-ETH / ESP32-P4-NANO). REF_CLK carries a 50 MHz reference clock
/// generated by the IP101GRI from its 25 MHz crystal:
///
/// <table>
/// <tr><th>Signal</th><th>GPIO</th></tr>
/// <tr><td>REF_CLK</td><td>50</td></tr>
/// <tr><td>TX_EN</td><td>49</td></tr>
/// <tr><td>TXD0</td><td>34</td></tr>
/// <tr><td>TXD1</td><td>35 (also the BOOT key / boot-strap pin, see below)</td></tr>
/// <tr><td>CRS_DV</td><td>28</td></tr>
/// <tr><td>RXD0</td><td>29</td></tr>
/// <tr><td>RXD1</td><td>30</td></tr>
/// <tr><td>MDC</td><td>31</td></tr>
/// <tr><td>MDIO</td><td>52</td></tr>
/// <tr><td>PHY_RST</td><td>51</td></tr>
/// </table>
///
/// - Audio: the ES8311 codec (I2S: MCLK=13, BCLK=12, WS/LRCK=10, DSDIN=9,
///   ASDOUT=11), the NS4150B speaker amplifier (enable=GPIO53) and the
///   analog microphone, through the espp::Audio component: mono playback and
///   recording, full duplex on one I2S bus.
///
/// Other on-board hardware not (yet) wrapped by this BSP (pin data from the
/// Waveshare schematic, see the component README):
/// - microSD / TF slot on the fixed 4-bit SDMMC pins
///   (CLK=43, CMD=44, D0..D3=39/40/41/42; pull-ups powered from LDO_VO4).
/// - MIPI-DSI and MIPI-CSI 15-pin (Raspberry-Pi-style) connectors; panels and
///   cameras are sold separately (the Kit-C / Kit-D bundles include them).
/// - USB-A: native USB 2.0 OTG HS. USB-C: CH343P USB-UART console on
///   UART0 (TX=GPIO37, RX=GPIO38) with auto-reset/boot circuitry.
/// - The red LED next to the RJ45 is a 5 V power indicator, and the RJ45
///   green/yellow LEDs are driven by the PHY — none are GPIO-controllable.
///
/// \note The BOOT key (Key1) is wired to GPIO35, which per the schematic is
///       also the RMII TXD1 line to the IP101GRI. GPIO35 is the ESP32-P4's
///       boot-strap pin, sampled only at reset — once the EMAC is running the
///       pin is a TXD1 output, so the BOOT key cannot be used as a runtime
///       input. Like the other ESP32-P4 RMII BSPs (ESP32-P4-ETH /
///       ESP32-P4-NANO, identical pinout) this BSP therefore does not expose
///       a button API; the key is only useful for entering the serial
///       bootloader at reset.
///
/// \note Assumption pending hardware verification: PHY address 1 (PHY_AD0 is
///       strapped high through a 5.1 kΩ pull-up like the ESP32-P4-ETH).
///
/// The class is a singleton and can be accessed via get().
///
/// \section esp32_p4_wifi6_poe_eth_example Example
/// \subsection esp32_p4_wifi6_poe_eth_get_instance Get Instance
/// \snippet esp32_p4_wifi6_poe_eth_example.cpp esp32 p4 wifi6 poe eth get instance
/// \subsection esp32_p4_wifi6_poe_eth_dhcp_server DHCP Server
/// \snippet esp32_p4_wifi6_poe_eth_example.cpp esp32 p4 wifi6 poe eth dhcp server
/// \subsection esp32_p4_wifi6_poe_eth_dhcp_client DHCP Client
/// \snippet esp32_p4_wifi6_poe_eth_example.cpp esp32 p4 wifi6 poe eth dhcp client
/// \subsection esp32_p4_wifi6_poe_eth_audio Audio
/// \snippet esp32_p4_wifi6_poe_eth_example.cpp esp32 p4 wifi6 poe eth audio
class Esp32P4Wifi6PoeEth : public BaseComponent {
public:
  /// Callback invoked (SERVER mode only) each time the DHCP server assigns an
  /// IP address to a connected client.
  using client_ip_callback_t = std::function<void(esp_ip4_addr_t ip, std::array<uint8_t, 6> mac)>;

  /// Callback invoked when the Ethernet link state changes (comes up or goes
  /// down) or when the IP address is lost.
  /// \note Runs in the ESP-IDF event-loop task context — return quickly, do not block.
  using EthernetLinkCallback = std::function<void()>;

  /// Callback invoked when the interface obtains an IPv4 address.
  /// \param ip The assigned IPv4 address.
  /// \note Runs in the ESP-IDF event-loop task context — return quickly, do not block.
  using EthernetIpCallback = std::function<void(esp_ip4_addr_t ip)>;

  /// DHCP operating mode for the Ethernet interface
  enum class DhcpMode {
    CLIENT, ///< DHCP client — acquire an IP from an upstream server (default)
    SERVER, ///< DHCP server — assign IPs to hosts connected to this interface
  };

  /// Static IP configuration used when operating as a DHCP server.
  /// Leave \c ip_info zero-initialised to use the built-in defaults
  /// (192.168.4.1 / 255.255.255.0 / gw 192.168.4.1).
  struct ServerConfig {
    esp_netif_ip_info_t ip_info{};                    ///< zero-initialised → 192.168.4.1/24
    client_ip_callback_t on_client_assigned{nullptr}; ///< Called for each assigned client IP.
  };

  /// Configuration for the Ethernet interface.
  struct EthernetConfig {
    DhcpMode mode{DhcpMode::CLIENT};            ///< DHCP operating mode.
    ServerConfig server_config{};               ///< Only used when mode == SERVER.
    EthernetLinkCallback on_link_up{nullptr};   ///< Physical link came up.
    EthernetLinkCallback on_link_down{nullptr}; ///< Physical link went down.
    EthernetIpCallback on_got_ip{nullptr};      ///< Interface obtained an IPv4 address.
    EthernetLinkCallback on_lost_ip{nullptr};   ///< Interface lost its IPv4 address.
  };

  /// @brief Access the singleton instance
  /// @return Reference to the singleton instance
  static Esp32P4Wifi6PoeEth &get() {
    static Esp32P4Wifi6PoeEth instance;
    return instance;
  }

  Esp32P4Wifi6PoeEth(const Esp32P4Wifi6PoeEth &) = delete;
  Esp32P4Wifi6PoeEth &operator=(const Esp32P4Wifi6PoeEth &) = delete;
  Esp32P4Wifi6PoeEth(Esp32P4Wifi6PoeEth &&) = delete;
  Esp32P4Wifi6PoeEth &operator=(Esp32P4Wifi6PoeEth &&) = delete;

  /// Get a reference to the internal I2C bus (SDA=GPIO7, SCL=GPIO8)
  /// \return A reference to the internal I2C bus
  /// \note Shared by the on-board ES8311 audio codec (0x18) and the DSI / CSI
  ///       connectors and 40-pin header
  I2c &internal_i2c() { return internal_i2c_; }

  /////////////////////////////////////////////////////////////////////////////
  // Ethernet (EMAC + IP101GRI RMII PHY)
  /////////////////////////////////////////////////////////////////////////////

  /// Initialize the Ethernet interface (EMAC + IP101GRI RMII PHY).
  /// \param config  Ethernet configuration (DHCP mode, callbacks).
  ///                All fields have defaults so \c EthernetConfig{} gives a
  ///                plain DHCP-client interface with no callbacks.
  /// \return True if Ethernet was successfully initialized and started, or if
  ///         it was already initialized (the call is idempotent). False only
  ///         on initialization failure.
  /// \warning If Ethernet is already initialized, the provided \p config is
  ///          IGNORED and a warning is logged -- the interface keeps running
  ///          with its original configuration (reconfiguration is not
  ///          supported).
  /// \note Requires the ESP-IDF TCP/IP stack and default event loop. The
  ///       underlying espp::Ethernet component calls esp_netif_init() and
  ///       esp_event_loop_create_default() during its initialize(), so they
  ///       are created here if the application has not already done so.
  bool initialize_ethernet(const EthernetConfig &config);

  /// Initialize Ethernet with default configuration (DHCP client mode).
  /// \return True if Ethernet was successfully initialized and started, or if
  ///         it was already initialized (the call is idempotent). False only
  ///         on initialization failure.
  bool initialize_ethernet();

  /// Check whether the interface has a usable IP address
  /// (DHCP lease granted in CLIENT mode, or link is up in SERVER mode).
  /// \return True if the interface is connected with a valid IP.
  bool is_ethernet_connected() const { return ethernet_ && ethernet_->is_connected(); }

  /// Get the most recently acquired IPv4 address (0 if none).
  /// \return The IPv4 address.
  esp_ip4_addr_t ethernet_ip() const { return ethernet_ ? ethernet_->ip() : esp_ip4_addr_t{}; }

  /////////////////////////////////////////////////////////////////////////////
  // Audio (ES8311 codec + NS4150B amplifier + analog microphone)
  /////////////////////////////////////////////////////////////////////////////

  /// How initialize_audio() sets the audio system up: the application's side of
  /// espp::Audio (the board's wiring is filled in by initialize_audio()). Start
  /// from default_audio_config() to keep this board's defaults.
  /// - sample_rate: The audio sample rate, in Hz: 8000, 11025, 16000, 22050,
  ///   24000, 32000, 44100 or 48000 (the ES8311's clock coefficients)
  /// - playback_enabled: Set up playback: the I2S TX channel, the ES8311 DAC,
  ///   the speaker and the playback task. Without it play_audio() queues
  ///   nothing.
  /// - recording_enabled: Set up recording: the I2S RX channel, the ES8311 ADC
  ///   (the onboard microphone) and the microphone task. Without it
  ///   start_audio_recording() fails.
  /// - playback_buffer_size / playback_buffer_caps: the stream play_audio()
  ///   queues into (0: about 67 ms of audio; larger lets one play_audio() call
  ///   queue a whole UI sound, e.g. in MALLOC_CAP_SPIRAM)
  /// - playback_task_config / recording_task_config: the audio tasks (the
  ///   recording callback runs on the recording task)
  /// \note Each I2S channel has a DMA ring of about 11.5 KB of internal DMA-
  ///       capable RAM, and each task's stack is in internal RAM too, so an
  ///       application that only plays (or only records) saves that memory by
  ///       turning the other direction off.
  using AudioConfig = espp::Audio::AppConfig;

  /// The board's default AudioConfig: 48 kHz, playback and recording, and the
  /// tasks "poe audio out" / "poe audio in" with this board's stack, priority
  /// and core.
  /// \return The default AudioConfig
  static AudioConfig default_audio_config();

  /// Initialize the audio system with the default AudioConfig: ES8311
  /// playback and recording at 48 kHz
  /// \return true if the audio system was successfully initialized, false otherwise
  bool initialize_audio();

  /// Initialize the audio system (ES8311 codec + NS4150B amplifier)
  /// \param config The sample rate, which directions to set up, the playback
  ///        buffer and the task configuration
  /// \return true if the audio system was successfully initialized, false
  ///         otherwise (also when neither playback nor recording is enabled,
  ///         or the sample rate is not one the ES8311 supports)
  /// \note A failure part way through undoes what was set up before it (the
  ///       I2S channels and their DMA rings, the stream buffer, the tasks, the
  ///       codec), so the call can be retried.
  bool initialize_audio(const AudioConfig &config);

  /// Stop the audio system and free what initialize_audio() set up (the
  /// speaker is switched off). Idempotent.
  /// \note The audio methods below may be called from any task meanwhile,
  ///       but initialize_audio() and deinitialize_audio() must not run
  ///       concurrently with each other, nor from an audio callback.
  void deinitialize_audio();

  /// Whether the audio system is initialized
  /// \return True if initialize_audio() succeeded (until deinitialize_audio())
  bool is_audio_initialized() const {
    auto audio = audio_.load();
    return audio && audio->is_initialized();
  }

  /// The audio component, for anything the BSP methods below do not expose
  /// \return The audio component, or nullptr before initialize_audio()
  /// \note deinitialize_audio() releases the hardware even while the returned
  ///       pointer is held: the object is then uninitialized (its methods
  ///       fail / return 0), and a later initialize_audio() makes a new one.
  std::shared_ptr<espp::Audio> audio() const { return audio_.load(); }

  /// Enable or disable the speaker amplifier (NS4150B)
  /// \param enable True to enable, false to disable
  /// \note initialize_audio() enables it when playback is set up.
  void enable_audio(bool enable);

  /// Set the audio volume
  /// \param volume The volume as a percentage (0-100)
  /// \note Before initialize_audio() (or without playback) the value is
  ///       stored and applied when playback starts.
  void volume(float volume);

  /// Get the audio volume
  /// \return The volume as a percentage (0-100)
  float volume() const;

  /// Mute or unmute the audio
  /// \param mute True to mute, false to unmute
  /// \note Before initialize_audio() (or without playback) the value is
  ///       stored and applied when playback starts.
  void mute(bool mute);

  /// Check if audio is muted
  /// \return True if muted, false otherwise
  bool is_muted() const;

  /// Get the audio sample rate
  /// \return The audio sample rate, in Hz
  uint32_t audio_sample_rate() const;

  /// Set the audio sample rate (the I2S clocks and the codec). The audio
  /// queued for playback is dropped, since it was for the old rate.
  /// \param sample_rate The audio sample rate, in Hz
  /// \return True on success (false before initialize_audio(), or if the
  ///         ES8311 does not support the rate: the previous rate is kept)
  bool audio_sample_rate(uint32_t sample_rate);

  /// Get the audio buffer size
  /// \return The size of one playback block, in bytes (1/60 s of audio)
  size_t audio_buffer_size() const;

  /// Play audio data
  /// \param data The audio data to play (16-bit signed mono samples)
  /// \param num_bytes The number of bytes to play
  /// \return The number of bytes actually queued (may be less than \p
  ///         num_bytes if the internal stream buffer is full)
  /// \note This function is non-blocking and queues the data for the audio
  ///       task to play; to stream data larger than the internal buffer,
  ///       call it repeatedly, advancing by the returned number of bytes
  ///       (or make the buffer larger: AudioConfig::playback_buffer_size)
  /// \note Must be called from task context, not from an ISR.
  size_t play_audio(const uint8_t *data, size_t num_bytes);

  /// Play audio data
  /// \param data The audio data to play (16-bit signed mono samples)
  /// \return The number of bytes actually queued (may be less than the data
  ///         size if the internal stream buffer is full)
  /// \note This function is non-blocking and queues the data for the audio
  ///       task to play; to stream data larger than the internal buffer,
  ///       call it repeatedly, advancing by the returned number of bytes
  ///       (or make the buffer larger: AudioConfig::playback_buffer_size)
  /// \note Must be called from task context, not from an ISR.
  size_t play_audio(std::span<const uint8_t> data);

  /// Drop any queued (not yet played) audio so a subsequent play_audio() starts
  /// immediately instead of waiting behind previously queued sound. Useful for
  /// UI sounds where a new event should restart the sound for maximum
  /// responsiveness.
  void clear_audio();

  /// Start recording audio
  /// \param callback Function to call with recorded audio data: 16-bit
  ///        signed mono samples (the onboard microphone, through the
  ///        ES8311's ADC) at audio_sample_rate()
  /// \return True if recording started successfully (false, among other
  ///         reasons, when initialize_audio() did not enable recording)
  /// \note The callback runs in the dedicated microphone task's context (a
  ///       separate task from audio playback), so keep it quick and non-
  ///       blocking and size that task's stack accordingly
  bool start_audio_recording(std::function<void(const uint8_t *data, size_t length)> callback);

  /// Stop recording audio. Once it returns the callback is not called again
  /// (unless it is called from the callback itself).
  void stop_audio_recording();

  /// Set the microphone volume
  /// \param volume The volume as a percentage (0 - 100), mapped onto the
  ///        ES8311 analog microphone gain range (0 dB - +42 dB)
  /// \note Before initialize_audio() (or without recording) the value is
  ///       stored and applied when recording starts.
  void microphone_volume(float volume);

  /// Get the microphone volume
  /// \return The microphone volume as a percentage (0 - 100)
  float microphone_volume() const;

  /////////////////////////////////////////////////////////////////////////////
  // ESP32-C6 (Wi-Fi 6 / BLE co-processor, ESP-Hosted over SDIO)
  /////////////////////////////////////////////////////////////////////////////
  // These constants document the ESP32-P4 <-> ESP32-C6 wiring for configuring
  // Espressif's esp_hosted component (see the example README). The BSP does
  // not bring up the C6 itself.
  static constexpr int c6_sdio_clk_io = 18; ///< P4 SDIO CLK -> C6 IO19 (SDIO_CLK)
  static constexpr int c6_sdio_cmd_io = 19; ///< P4 SDIO CMD -> C6 IO18 (SDIO_CMD)
  static constexpr int c6_sdio_d0_io = 14;  ///< P4 SDIO D0  -> C6 IO20 (SDIO_DATA0)
  static constexpr int c6_sdio_d1_io = 15;  ///< P4 SDIO D1  -> C6 IO21 (SDIO_DATA1)
  static constexpr int c6_sdio_d2_io = 16;  ///< P4 SDIO D2  -> C6 IO22 (SDIO_DATA2)
  static constexpr int c6_sdio_d3_io = 17;  ///< P4 SDIO D3  -> C6 IO23 (SDIO_DATA3)
  static constexpr int c6_reset_io = 54;    ///< P4 GPIO54 -> C6 EN (CHIP_PU) via 0 Ω
  static constexpr int c6_spare_io = 6;     ///< P4 GPIO6 -> C6 IO2 via 0 Ω (unused spare)

protected:
  Esp32P4Wifi6PoeEth();

  /////////////////////////////////////////////////////////////////////////////
  // RMII / EMAC pin constants (IP101GRI PHY)
  /////////////////////////////////////////////////////////////////////////////
  static constexpr int eth_mdc_io = 31;
  static constexpr int eth_mdio_io = 52;
  static constexpr int eth_ref_clk_io = 50;
  static constexpr int eth_phy_reset_gpio = 51;
  static constexpr int eth_phy_addr = 1;
  static constexpr int eth_tx_en_io = 49;
  static constexpr int eth_txd0_io = 34;
  // NOTE: GPIO35 is shared with the BOOT key (P4 boot-strap pin, sampled only
  //       at reset) — it is exclusively the EMAC TXD1 output at runtime.
  static constexpr int eth_txd1_io = 35;
  static constexpr int eth_crs_dv_io = 28;
  static constexpr int eth_rxd0_io = 29;
  static constexpr int eth_rxd1_io = 30;

  /////////////////////////////////////////////////////////////////////////////
  // Internal I2C bus (ES8311 codec 0x18; DSI / CSI connectors; 40-pin header)
  /////////////////////////////////////////////////////////////////////////////
  static constexpr auto internal_i2c_port = I2C_NUM_0;
  static constexpr auto internal_i2c_clock_speed = 400 * 1000;
  static constexpr gpio_num_t internal_i2c_sda = GPIO_NUM_7;
  static constexpr gpio_num_t internal_i2c_scl = GPIO_NUM_8;

  /////////////////////////////////////////////////////////////////////////////
  // Audio (ES8311 + NS4150B), I2S peripheral
  /////////////////////////////////////////////////////////////////////////////
  static constexpr uint8_t es8311_i2c_address = 0x18;
  static constexpr auto audio_i2s_port = I2S_NUM_0;
  static constexpr gpio_num_t audio_mclk_io = GPIO_NUM_13;      // MCLK
  static constexpr gpio_num_t audio_sclk_io = GPIO_NUM_12;      // BCLK
  static constexpr gpio_num_t audio_lrck_io = GPIO_NUM_10;      // WS/LRCK
  static constexpr gpio_num_t audio_dout_io = GPIO_NUM_9;       // P4 -> codec DSDIN
  static constexpr gpio_num_t audio_din_io = GPIO_NUM_11;       // codec ASDOUT -> P4
  static constexpr gpio_num_t audio_pa_enable_io = GPIO_NUM_53; // NS4150B enable

  /////////////////////////////////////////////////////////////////////////////
  // Member variables
  /////////////////////////////////////////////////////////////////////////////

  // The board's RMII Ethernet is driven by the reusable espp::Ethernet component
  // (this BSP just supplies the board-specific pins / PHY).
  std::unique_ptr<espp::Ethernet> ethernet_;

  // Internal I2C bus
  I2c internal_i2c_{{.port = internal_i2c_port,
                     .sda_io_num = internal_i2c_sda,
                     .scl_io_num = internal_i2c_scl,
                     .sda_pullup_en = GPIO_PULLUP_ENABLE,
                     .scl_pullup_en = GPIO_PULLUP_ENABLE,
                     .clk_speed = internal_i2c_clock_speed}};

  // Audio (espp::Audio, created by initialize_audio()). atomic: the
  // forwarders may run on any task while initialize_audio() /
  // deinitialize_audio() publish / unpublish it
  std::atomic<std::shared_ptr<espp::Audio>> audio_;
  std::shared_ptr<espp::Es8311Codec> es8311_;
  std::shared_ptr<I2c::Device<uint8_t>> es8311_i2c_device_;
  // the settings, kept across initialize_audio() / deinitialize_audio() and
  // passed to espp::Audio as its initial values
  std::atomic<float> volume_{50.0f};
  std::atomic<bool> mute_{false};
  // microphone volume (percent), mapped onto the ES8311 analog gain range
  std::atomic<float> mic_volume_{70.0f};
}; // class Esp32P4Wifi6PoeEth
} // namespace espp
