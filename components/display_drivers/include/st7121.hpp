#pragma once

#include <array>

#include "display_drivers.hpp"

namespace espp {

/**
 * @brief Driver for the Sitronix ST7121 TDDI (touch-and-display driver
 *        integration) MIPI-DSI panel controller.
 *
 * The ST7121 is the successor to the ST7123 used on newer M5Stack Tab5
 * revisions. Like the ST7123 it integrates the touch engine with the display
 * driver (touch is served by the same chip on I2C address 0x55 and speaks the
 * same protocol as the ST7123 — use espp::St7123Touch), but it requires a
 * DIFFERENT vendor initialization sequence, a lower DSI lane rate, and its own
 * DPI porch timing. The two parts cannot be distinguished by their DSI ID;
 * read the touch firmware-version register instead (1 = ST7121, 3 = ST7123).
 *
 * The vendor init table below is transcribed from M5Stack's M5GFX
 * (src/lgfx/v1/platforms/esp32p4/Panel_ST7121.hpp, FreeBSD license,
 * (c) lovyan03 and M5Stack), which is the reference adaptation for this
 * panel revision.
 */
class St7121 : public display_drivers::MipiDbiDisplayDriver {
  static constexpr uint8_t GS_BIT = 1 << 0;
  static constexpr uint8_t SS_BIT = 1 << 1;
  static constexpr uint8_t BGR_BIT = 1 << 3;

public:
  enum class Command : uint8_t {
    NOP = 0x00,
    SWRESET = 0x01,
    RDDID = 0x04,
    SLPIN = 0x10,
    SLPOUT = 0x11,
    NORON = 0x13,
    INVOFF = 0x20,
    INVON = 0x21,
    DISPOFF = 0x28,
    DISPON = 0x29,
    CASET = 0x2A,
    RASET = 0x2B,
    RAMWR = 0x2C,
    RAMRD = 0x2E,
    TEON = 0x35,
    MADCTL = 0x36,
    COLMOD = 0x3A,
  };

  explicit St7121(const display_drivers::Config &config)
      : MipiDbiDisplayDriver(config,
                             {.column_address_command = static_cast<uint8_t>(Command::CASET),
                              .row_address_command = static_cast<uint8_t>(Command::RASET),
                              .memory_write_command = static_cast<uint8_t>(Command::RAMWR)}) {}

  static constexpr const char *id() { return "ST7121"; }

  bool initialize() override {
    display_drivers::init_pins(config_.reset_pin, config_.data_command_pin, config_.reset_value);

    // Honor the controller's current rotation state (defaults to LANDSCAPE,
    // but a set_rotation() issued before initialize() is respected).
    auto madctl = make_madctl(rotation_);

    uint8_t colmod = 0x55;
    switch (config_.bits_per_pixel) {
    case 16:
      colmod = 0x55;
      break;
    case 18:
      colmod = 0x66;
      break;
    case 24:
      colmod = 0x77;
      break;
    default:
      break;
    }

    // Vendor init sequence from M5GFX Panel_ST7121 (see class comment). Note
    // the command-page unlock key is 0x71 0x21 (vs 0x71 0x23 on the ST7123).
    auto init_commands = std::to_array<display_drivers::DisplayInitCmd<>>({
        {0x60, {0x71, 0x21, 0xA2}, 0},
        {0x60, {0x71, 0x21, 0xA3}, 0},
        {0x60, {0x71, 0x21, 0xA4}, 0},
        {0x78, {0x21}, 0},
        {0x79, {0xEF}, 0},
        {0xA4, {0x31}, 0},
        {0xB7, {0x00, 0x00, 0x5F, 0x5F, 0x44, 0x1A}, 0},
        {0xB0, {0x22, 0x6B, 0x11, 0x89, 0x25, 0x43, 0x43}, 0},
        {0xBF, {0xA7, 0xA7}, 0},
        {0xA5, {0xF0, 0x03}, 0},
        {0xD7, {0x10, 0x2C, 0x14, 0x2A, 0x80, 0x80}, 0},
        // NOTE: the 0x71 0x23 bytes here are NOT the vendor page-unlock key
        // (that is the 0x60 command above, which uses 0x71 0x21 on this part);
        // they are the 0x90 command's own payload, verbatim from the M5GFX
        // reference for the ST7121.
        {0x90, {0x71, 0x23, 0x5A, 0x20, 0x24, 0x11, 0x21}, 0},
        {0xA3,
         {0x80, 0x01, 0x8C, 0xFF, 0x45, 0x00, 0x00, 0x00, 0x00, 0x00, 0x46, 0x00, 0x00,
          0x1E, 0x5C, 0x1E, 0x80, 0x10, 0x00, 0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x46,
          0x00, 0x00, 0x1E, 0x5C, 0x1E, 0x80, 0x10, 0xEF, 0x58, 0x00, 0x00, 0x00, 0xFF},
         0},
        {0xA6,
         {0x0A, 0x00, 0x24, 0x71, 0x36, 0x00, 0x00, 0x00, 0x68, 0x68, 0x91, 0xFF, 0x00, 0x24,
          0x71, 0x37, 0x00, 0x00, 0x00, 0x68, 0x68, 0x91, 0xFF, 0x00, 0x24, 0x71, 0x00, 0x00,
          0x00, 0x00, 0x68, 0x68, 0x91, 0xFF, 0x00, 0x2C, 0x71, 0x00, 0x01, 0x00, 0x00, 0x68,
          0x68, 0xFF, 0xFF, 0x00, 0x08, 0x80, 0x08, 0x80, 0x06, 0x00, 0x00, 0x00, 0x00},
         0},
        {0xA7,
         {0x1A, 0x1A, 0xC0, 0x64, 0x40, 0x04, 0x15, 0x40, 0x00, 0x40, 0x00, 0x68, 0x68, 0x91, 0xFF,
          0x08, 0x80, 0x64, 0x40, 0x26, 0x37, 0x40, 0x00, 0x00, 0x00, 0x68, 0x68, 0x91, 0xFF, 0x08,
          0x80, 0x64, 0x40, 0x8C, 0x9D, 0x40, 0x00, 0x00, 0x00, 0x68, 0x68, 0x91, 0xFF, 0x08, 0x80,
          0x64, 0x40, 0xAE, 0xBF, 0x00, 0x00, 0x20, 0x00, 0x68, 0x68, 0x91, 0xFF, 0x08, 0x80, 0x79},
         0},
        {0xAC,
         {0x1D, 0x18, 0x19, 0x1D, 0x18, 0x19, 0x04, 0x1C, 0x1D, 0x08, 0x0A, 0x10, 0x12, 0x0C, 0x0E,
          0x14, 0x16, 0x00, 0x1D, 0x1D, 0x1D, 0x1D, 0x1D, 0x18, 0x19, 0x1D, 0x18, 0x19, 0x06, 0x1C,
          0x1D, 0x09, 0x0B, 0x11, 0x13, 0x0D, 0x0F, 0x15, 0x17, 0x02, 0x1D, 0x1D, 0x1D, 0x1D},
         0},
        {0xAD,
         {0x0C, 0x40, 0x46, 0x00, 0x07, 0x4B, 0x4B, 0xFF, 0xFF, 0xF0, 0x40, 0x0E, 0x01,
          0x07, 0x42, 0x42, 0xFF, 0xFF, 0x01, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF},
         0},
        {0xAE, {0xF0, 0xFF, 0x03, 0xF0, 0xFF, 0x03, 0x00}, 0},
        {0xB2,
         {0x15, 0x19, 0x05, 0x23, 0x49, 0x2D, 0x03, 0x2E, 0x5C, 0xD2, 0xFF, 0x10, 0x60, 0xFD, 0x20,
          0xC0, 0x00},
         0},
        {0xE8,
         {0x20, 0x60, 0x04, 0x8E, 0x8E, 0x3E, 0x04, 0xDC, 0xDC, 0x3E, 0x06, 0xFA, 0x26, 0x3E},
         0},
        {0x75, {0x03, 0x04}, 0},
        {0xE7,
         {0x4B, 0x00, 0x00, 0xBE, 0x4B, 0x8C, 0x20, 0x1A, 0xF0, 0x7D, 0x14, 0x7D, 0x14, 0x7D,
          0x14, 0x7D, 0x14, 0xFF, 0x00, 0x32, 0x30, 0x73, 0x00, 0x00, 0xC8, 0x6A, 0xFF, 0x5A,
          0x64, 0x38, 0x88, 0x15, 0xB1, 0x01, 0x01, 0x64, 0x01, 0x01, 0x7C, 0xFF, 0x1A, 0x51},
         0},
        {0xE1, {0x0C, 0x0C}, 0},
        {0xEA, {0x15, 0x00, 0x01}, 0},
        {0xC8,
         {0x00, 0x00, 0x04, 0x08, 0x10, 0x00, 0x1F, 0x01, 0x39, 0x3E, 0x00, 0x78, 0x06,
          0xE2, 0x02, 0x11, 0x33, 0x01, 0x7A, 0x0D, 0x21, 0xC4, 0x0B, 0x19, 0x08, 0x32,
          0xA0, 0x08, 0x1A, 0x0A, 0xF3, 0x7F, 0x0E, 0xC5, 0xE8, 0x03, 0xFF},
         0},
        {0xC9,
         {0x00, 0x00, 0x04, 0x08, 0x10, 0x00, 0x1F, 0x01, 0x39, 0x3E, 0x00, 0x78, 0x06,
          0xE2, 0x02, 0x11, 0x33, 0x01, 0x7A, 0x0D, 0x21, 0xC4, 0x0B, 0x19, 0x08, 0x32,
          0xA0, 0x08, 0x1A, 0x0A, 0xF3, 0x7F, 0x0E, 0xC5, 0xE8, 0x03, 0xFF},
         0},
        {0x60, {0x71, 0x21, 0x00}, 0}, // relock the vendor command page
        // M5GFX delays: 80 ms after SLPOUT, 800 ms after DISPON. The long
        // display-on settle matters on this panel: cutting it short is a known
        // cause of grey/blank first frames on ST71xx Tab5 units.
        {static_cast<uint8_t>(Command::SLPOUT), {}, 80},
        {static_cast<uint8_t>(Command::DISPON), {}, 800},
        {static_cast<uint8_t>(Command::TEON), {0x00}, 0},
        {static_cast<uint8_t>(Command::MADCTL), {madctl}, 0},
        {static_cast<uint8_t>(Command::COLMOD), {colmod}, 0},
    });

    send_commands(init_commands);
    return true;
  }

  void set_rotation(const DisplayRotation &rotation) override {
    Controller::set_rotation(rotation);
    auto data = std::array<uint8_t, 1>{make_madctl(rotation)};
    std::scoped_lock lock(io_mutex_);
    write_command(static_cast<uint8_t>(Command::MADCTL), data, 0);
  }

private:
  uint8_t make_madctl(DisplayRotation rotation) const {
    auto value = display_drivers::make_madctl_base(config_, BGR_BIT, GS_BIT, SS_BIT, 0);
    return display_drivers::apply_standard_rotation(value, config_, rotation, GS_BIT, SS_BIT, 0);
  }
};

} // namespace espp
